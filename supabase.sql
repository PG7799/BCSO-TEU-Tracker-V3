create table if not exists public.teu_events (
    id bigint generated by default as identity primary key,
    category text not null check (
        category in (
            'arrest',
            'pit',
            'pursuit',
            'citation',
            'crash',
            'grappler',
            'felony_stop',
            'assist',
            'dui',
            'other'
        )
    ),
    member text,
    activity_date date not null,
    month_start date not null,
    notes text,
    created_at timestamptz not null default now()
);

create index if not exists teu_events_month_idx
on public.teu_events(month_start, created_at desc);

create index if not exists teu_events_category_idx
on public.teu_events(category);

create index if not exists teu_events_member_idx
on public.teu_events(member);

create table if not exists public.teu_admins (
    user_id uuid primary key references auth.users(id) on delete cascade
);

alter table public.teu_events enable row level security;
alter table public.teu_admins enable row level security;

drop policy if exists "TEU public read" on public.teu_events;
create policy "TEU public read"
on public.teu_events
for select
to anon, authenticated
using (true);

drop policy if exists "TEU public insert" on public.teu_events;
create policy "TEU public insert"
on public.teu_events
for insert
to anon, authenticated
with check (
    month_start = date_trunc('month', activity_date)::date
);

drop policy if exists "Admins can read own admin record" on public.teu_admins;
create policy "Admins can read own admin record"
on public.teu_admins
for select
to authenticated
using (auth.uid() = user_id);

create or replace function public.reset_current_teu_month(target_month date)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
    deleted_count integer;
begin
    if not exists (
        select 1
        from public.teu_admins
        where user_id = auth.uid()
    ) then
        raise exception 'Not authorized';
    end if;

    delete from public.teu_events
    where month_start = date_trunc('month', target_month)::date;

    get diagnostics deleted_count = row_count;
    return deleted_count;
end;
$$;

revoke all on function public.reset_current_teu_month(date) from public;
grant execute on function public.reset_current_teu_month(date) to authenticated;

do $$
begin
    alter publication supabase_realtime add table public.teu_events;
exception
    when duplicate_object then null;
end $$;

