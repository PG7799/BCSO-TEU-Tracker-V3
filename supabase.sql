create table if not exists public.teu_roster (
    id bigint generated by default as identity primary key,
    callsign text not null,
    name text not null,
    rank text not null,
    subdivision_rank text not null check (
        subdivision_rank in (
            'TEU Traffic Member',
            'FTO',
            'Co Commander',
            'Commander'
        )
    ),
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists teu_roster_active_idx
on public.teu_roster(active, callsign);

alter table public.teu_roster enable row level security;

drop policy if exists "TEU roster public read" on public.teu_roster;
create policy "TEU roster public read"
on public.teu_roster for select
to anon, authenticated
using (true);

drop policy if exists "TEU admins can insert roster" on public.teu_roster;
create policy "TEU admins can insert roster"
on public.teu_roster for insert
to authenticated
with check (exists (
    select 1 from public.teu_admins where user_id = auth.uid()
));

drop policy if exists "TEU admins can update roster" on public.teu_roster;
create policy "TEU admins can update roster"
on public.teu_roster for update
to authenticated
using (exists (
    select 1 from public.teu_admins where user_id = auth.uid()
))
with check (exists (
    select 1 from public.teu_admins where user_id = auth.uid()
));

drop policy if exists "TEU admins can delete roster" on public.teu_roster;
create policy "TEU admins can delete roster"
on public.teu_roster for delete
to authenticated
using (exists (
    select 1 from public.teu_admins where user_id = auth.uid()
));

create or replace function public.update_teu_roster_timestamp()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists teu_roster_updated_at on public.teu_roster;
create trigger teu_roster_updated_at
before update on public.teu_roster
for each row execute function public.update_teu_roster_timestamp();

do $$
begin
  alter publication supabase_realtime add table public.teu_roster;
exception when duplicate_object then null;
end $$;
